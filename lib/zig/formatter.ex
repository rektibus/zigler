defmodule Zig.Formatter do
  @behaviour Mix.Tasks.Format

  def features(_opts), do: [sigils: [:Z], extensions: [".zig"]]

  def format(contents, _opts) do
    if String.starts_with?(contents, "// this code is autogenerated"),
      do: contents,
      else: format_string(contents)
  end

  def format_string(contents) do
    path = Path.join(System.tmp_dir!(), "zigler-format-#{System.pid()}-#{System.unique_integer([:positive])}.zig")
    File.write!(path, contents, [:exclusive])

    try do
      case System.cmd(Zig.Command.executable_path(), ["fmt", path], stderr_to_stdout: true) do
        {_, 0} -> File.read!(path)
        {_, _} -> contents
      end
    after
      File.rm!(path)
    end
  end
end
